#!/usr/bin/env python3
"""Write the module sources and the generated macro test from the Box2D headers.

- src/box2d.cppm exports, by `export using` and under their upstream global
  names, every type (structs, enums, function types, aliases), opaque struct,
  enumerator, B2_API function, inline function (the B2_INLINE math and id
  functions are `inline`, external linkage, in C++), C++ vector operator and
  the one exported variable (b2_lengthUnitsPerMeter) of the installed
  headers. Its `static const` objects (b2Vec2_zero, b2Rot_identity,
  b2_nullBodyId …) have internal linkage and cannot be exported as they are:
  each is an `inline constexpr` of the same type and initializer in
  mcpplibs::mwrap::box2d, under the same name. It re-exports the macros module.
- src/macros.cppm holds, in mcpplibs::mwrap::box2d::macros under their own
  names:
    * the constant object-like macros (B2_PI, B2_MAX_POLYGON_VERTICES,
      B2_HASH_INIT, B2_DEFAULT_MASK_BITS, B2_VERSION_* …) as `inline
      constexpr` of the type of the macro's own expansion;
    * the object-like macros that read b2_lengthUnitsPerMeter (B2_HUGE,
      B2_LINEAR_SLOP, B2_SPECULATIVE_DISTANCE, B2_CONTACT_RECYCLE_DISTANCE,
      B2_MAX_AABB_MARGIN): that variable is set at run time by
      b2SetLengthUnitsPerMeter, so they are not constants. Each is an inline
      function of no arguments returning the macro's value, `B2_LINEAR_SLOP()`;
    * the function-like macros over ids (B2_IS_NULL, B2_IS_NON_NULL,
      B2_ID_EQUALS) as constexpr function templates whose body is the macro.
- tests/macros_mix_test.cpp checks each mapping against the raw header in a
  translation unit that includes it beside the import.

With --check, nothing is written and a difference fails.
"""
import argparse
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import GUARD as ASSERT_GUARD, fetch, surface  # noqa: E402

# Macros that stay macros, in <mwrap/box2d/macros.hpp> (which is <box2d/box2d.h>).
SIDE_HEADER = {
    'BOX2D_EXPORT': 'a declaration attribute (dllexport/dllimport/visibility; empty for the static library)',
    'B2_API': 'a declaration specifier (extern "C" and BOX2D_EXPORT)',
    'B2_INLINE': 'a declaration specifier (inline in C++, static inline in C)',
    'B2_FORCE_INLINE': 'a declaration specifier (inline with always_inline / __forceinline)',
    'B2_ID_INLINE': 'a declaration specifier (inline in C++, static inline in C)',
    'B2_ALIGN_AS': 'an alignment specifier (alignas / _Alignas)',
    'B2_LITERAL': 'C compound-literal syntax: (T) in C, T in C++',
    'B2_ZERO_INIT': 'a braced initializer ({} in C++), not a value of one type',
    'B2_NULL_ID': 'a braced initializer ({} in C++) for any id type, not a value of one type',
    'B2_BREAKPOINT': 'a statement that traps into the debugger (__debugbreak / __builtin_trap)',
    'B2_ASSERT': 'an assertion: stringifies its condition and reports __FILE__ / __LINE__ of the call site',
    'B2_VALIDATE': 'an assertion in validation builds (B2_ASSERT), nothing otherwise',
}

RUNTIME = 'b2_lengthUnitsPerMeter'

GUARD = '#include <box2d/box2d.h>'


def classify(sf):
    """(constants, runtime, functions): the mapped macros, in header order."""
    constants, runtime, functions = [], [], []
    for macro in sf.macros.values():
        if macro.name in SIDE_HEADER:
            continue
        if macro.params is not None:
            functions.append(macro)
        elif reads_runtime(sf, macro.name):
            runtime.append(macro.name)
        else:
            constants.append(macro.name)
    return constants, runtime, functions


def reads_runtime(sf, name: str, seen=()) -> bool:
    body = sf.macros[name].body
    if re.search(r'\b' + RUNTIME + r'\b', body):
        return True
    return any(reads_runtime(sf, n, seen + (name,)) for n in re.findall(r'\b\w+\b', body)
               if n in sf.macros and n not in seen and n != name)


ROOT_HEADER = '''// Generated by tools/gen_exports.py from the Box2D 3.2.0 headers — do not edit
// by hand.
//
// mcpplibs.mwrap.box2d — Box2D v3, the 2D rigid-body physics engine for games,
// as a C++ module. Every exported name is the upstream global of
// <box2d/box2d.h>, unchanged: the types, enums and their enumerators, every
// B2_API function (worlds, bodies, shapes, chains, joints, contacts, events,
// queries, the collision and geometry functions, recording and replay), the
// inline math and id functions, the C++ vector operators and
// b2_lengthUnitsPerMeter. The headers' `static const` objects (internal
// linkage) are constants of the same type and value in mcpplibs::mwrap::box2d.
// The root also re-exports the macro mappings. The library is compat.box2d,
// built from the same release (single precision, upstream's default SIMD,
// -ffp-contract=off).
module;
''' + GUARD + '''

export module mcpplibs.mwrap.box2d;

export import mcpplibs.mwrap.box2d.macros;
'''


def render_root(sf) -> str:
    out = [ROOT_HEADER]
    out.append(f'// types: structs, enums, function types and aliases ({len(sf.types)})')
    out += [f'export using ::{n};' for n in sf.types]
    out.append(f'\n// opaque structs, declared and not defined ({len(sf.opaque)})')
    out += [f'export using ::{n};' for n in sf.opaque]
    by_enum: dict[str, list[str]] = {}
    for e, t in sf.enumerators.items():
        by_enum.setdefault(t, []).append(e)
    out.append(f'\n// enumerators ({len(sf.enumerators)})')
    for t, names in by_enum.items():
        out.append(f'// {t} ({len(names)})')
        out += [f'export using ::{n};' for n in names]
    plain = [n for n in sf.functions if n not in sf.guarded]
    out.append(f'\n// B2_API functions ({len(sf.functions)})')
    out += [f'export using ::{n};' for n in plain]
    for n in sorted(sf.guarded):
        out += [f'// declared, and defined by the library, only under {ASSERT_GUARD}',
                f'#if {ASSERT_GUARD}', f'export using ::{n};', '#endif']
    out.append(f'\n// inline functions: B2_INLINE, B2_FORCE_INLINE and B2_ID_INLINE are `inline` in C++ ({len(sf.inline)})')
    out += [f'export using ::{n};' for n in sf.inline]
    out.append(f'\n// the C++ vector operators of math_functions.h ({len(sf.operators)})')
    out += [f'export using ::{n};' for n in sf.operators]
    out.append(f'\n// variables ({len(sf.variables)})')
    out += [f'export using ::{n};' for n in sf.variables]
    out.append(f'''
// The headers' `static const` objects ({len(sf.constants)}) have internal linkage: a
// named module cannot export them. Each is a constant of the same type and
// initializer here, under the same name.
export namespace mcpplibs::mwrap::box2d {{
''')
    out += [f'inline constexpr ::{c.type} {c.name} = {c.init};' for c in sf.constants]
    out.append('\n}  // namespace mcpplibs::mwrap::box2d')
    return '\n'.join(out) + '\n'


MACROS_HEADER = '''// Generated by tools/gen_exports.py from the Box2D 3.2.0 headers — do not edit
// by hand.
//
// mcpplibs.mwrap.box2d.macros — the macros of <box2d/box2d.h> that a C++
// entity can be, under the original names in mcpplibs::mwrap::box2d::macros:
//
//   - the constant object-like macros (B2_PI, B2_NULL_INDEX, B2_HASH_INIT,
//     B2_MAX_POLYGON_VERTICES, B2_MAX_WORKERS, B2_DEFAULT_CATEGORY_BITS,
//     B2_DEFAULT_MASK_BITS, B2_VERSION_* …) as `inline constexpr`, each of the
//     type its macro expands to (B2_PI is a `float`, as 3.14159265359f is;
//     B2_DEFAULT_MASK_BITS a `uint64_t`, as UINT64_MAX is);
//   - the object-like macros that read b2_lengthUnitsPerMeter (B2_HUGE,
//     B2_LINEAR_SLOP, B2_SPECULATIVE_DISTANCE, B2_CONTACT_RECYCLE_DISTANCE,
//     B2_MAX_AABB_MARGIN). b2SetLengthUnitsPerMeter changes that variable at
//     run time, so these are not constants: each is a function of no
//     arguments returning the macro's value at the call, `B2_LINEAR_SLOP()`;
//   - the function-like macros over ids (B2_IS_NULL, B2_IS_NON_NULL,
//     B2_ID_EQUALS) as constexpr function templates. Each body is the macro
//     itself, expanded on the parameters while the header's macros are
//     defined (the declarator is parenthesised so the name is not expanded):
//     the result has the macro's value and type for every id type. Each
//     argument is evaluated once, before the call (the macro evaluates its
//     arguments up to three times).
//
// Declaration specifiers, initializer syntax and the assertion macros stay
// macros, in <mwrap/box2d/macros.hpp>, included before the import.
// tools/check_exports.py accounts for every macro.
module;
''' + GUARD + '''
'''


def function(macro) -> list[str]:
    tparams = ', '.join(f'class T{i}' for i in range(len(macro.params)))
    params = ', '.join(f'T{i} {p}' for i, p in enumerate(macro.params))
    call = f'{macro.name}({", ".join(macro.params)})'
    return [f'template <{tparams}>', f'constexpr auto ({macro.name})({params}) noexcept {{ return {call}; }}']


def render_macros(sf) -> str:
    constants, runtime, functions = classify(sf)
    out = [MACROS_HEADER]
    out.append('export module mcpplibs.mwrap.box2d.macros;\n')
    out.append('// The header\'s values, taken while its macros are defined (module linkage).')
    out.append('namespace mwrap_box2d_capture {')
    out += [f'inline constexpr auto value_{n} = {n};' for n in constants]
    out += [f'inline auto value_{n}() noexcept {{ return {n}; }}' for n in runtime]
    out.append('}  // namespace mwrap_box2d_capture\n')
    out.append('// ── computation macros, defined while the header\'s macros are ──────────────')
    out.append('export namespace mcpplibs::mwrap::box2d::macros {\n')
    for macro in functions:
        out.append(f'// #define {macro.name}({", ".join(macro.params)}) {macro.body}')
        out += function(macro)
    out.append('\n}  // namespace mcpplibs::mwrap::box2d::macros\n')
    out.append('// Every mapped object-like name, so the definitions below are not rewritten.')
    out += [f'#undef {n}' for n in constants + runtime]
    out.append('\nnamespace c = mwrap_box2d_capture;\n')
    out.append('export namespace mcpplibs::mwrap::box2d::macros {\n')
    out.append('// ── constants ───────────────────────────────────────────────────────────────')
    out += [f'inline constexpr auto {n} = c::value_{n};' for n in constants]
    out.append('\n// ── values that read b2_lengthUnitsPerMeter at the call ─────────────────────')
    out += [f'inline auto {n}() noexcept {{ return c::value_{n}(); }}' for n in runtime]
    out.append('\n}  // namespace mcpplibs::mwrap::box2d::macros')
    return '\n'.join(out) + '\n'


TEST_HEADER = '''// Generated by tools/gen_exports.py from the Box2D 3.2.0 headers — do not edit
// by hand.
//
// Every mapping against the raw header, in one translation unit that includes
// <mwrap/box2d/macros.hpp> (that is, <box2d/box2d.h>) beside the import:
//
//   - each constant has its macro's type and value (the macro is set aside
//     with push_macro around the comparison: while it is defined it expands
//     even inside `m::NAME`);
//   - each length-unit value gives the macro's value and type, at the default
//     length unit and at another one set with b2SetLengthUnitsPerMeter;
//   - each id macro function gives the macro's value and type for null and
//     non-null ids of every id type, equal and unequal pairs; a function-like
//     macro is not expanded when its name is followed by `)`, so
//     `(m::NAME)(args)` calls the function beside the macro `NAME(args)`;
//   - each `static const` object of the headers equals, byte for byte and in
//     type, the module's constant of the same name.
#include <mwrap/box2d/macros.hpp>
#include <gtest/gtest.h>

import std;
import mcpplibs.mwrap.box2d;

namespace m = mcpplibs::mwrap::box2d::macros;
namespace b = mcpplibs::mwrap::box2d;
'''

TEST_SAMPLES = '''
namespace {

// Null and non-null ids of every id type but b2WorldId (B2_ID_EQUALS does not
// apply to it upstream: it has no world0).
template <class Id>
std::vector<Id> ids() {
    std::vector<Id> out;
    for (int index : {0, 1, 7, 0x7fffffff})
        for (int world : {0, 1, 3})
            for (int generation : {0, 1, 0xffff}) {
                Id id{};
                id.index1 = index;
                id.world0 = static_cast<std::uint16_t>(world);
                id.generation = static_cast<decltype(id.generation)>(generation);
                out.push_back(id);
            }
    return out;
}

template <class F>
void unary(F check) {
    for (auto v : ids<b2BodyId>()) check(v);
    for (auto v : ids<b2ShapeId>()) check(v);
    for (auto v : ids<b2ChainId>()) check(v);
    for (auto v : ids<b2JointId>()) check(v);
    for (auto v : ids<b2ContactId>()) check(v);
    for (int index : {0, 1, 0xffff}) check(b2WorldId{static_cast<std::uint16_t>(index), 1});
}
template <class F>
void binary(F check) {
    auto over = [&](const auto& values) {
        for (auto a : values)
            for (auto c : values) check(a, c);
    };
    over(ids<b2BodyId>());
    over(ids<b2ShapeId>());
    over(ids<b2JointId>());
    over(ids<b2ContactId>());
}

// Restores the length unit a test changes.
struct LengthUnits {
    explicit LengthUnits(float units) { b2SetLengthUnitsPerMeter(units); }
    ~LengthUnits() { b2SetLengthUnitsPerMeter(1.0f); }
};

}  // namespace
'''


def render_test(sf) -> str:
    constants, runtime, functions = classify(sf)
    out = [TEST_HEADER]
    out.append('// ── constants ───────────────────────────────────────────────────────────────')
    for n in constants:
        out.append(f'constexpr auto raw_{n} = {n};')
    for n in constants:
        out += [f'#pragma push_macro("{n}")', f'#undef {n}',
                f'static_assert(std::is_same_v<decltype(m::{n}), decltype(raw_{n})> && m::{n} == raw_{n});',
                f'#pragma pop_macro("{n}")']
    out.append('\n// ── the static const objects ────────────────────────────────────────────────')
    for c in sf.constants:
        out.append(f'static_assert(std::is_same_v<decltype(b::{c.name}), const ::{c.type}>);')
    out.append('')
    out.append('TEST(StaticConstants, SameBytes) {')
    for c in sf.constants:
        out.append(f'    EXPECT_EQ(std::memcmp(&b::{c.name}, &::{c.name}, sizeof(::{c.type})), 0) << "{c.name}";')
    out.append('}')
    out.append(TEST_SAMPLES)
    out.append('// ── values that read b2_lengthUnitsPerMeter ─────────────────────────────────')
    out.append('TEST(LengthUnitValues, FollowTheLengthUnit) {')
    out.append('    auto check = [] {')
    for n in runtime:
        out += [f'        auto raw_{n} = {n};',
                f'#pragma push_macro("{n}")', f'#undef {n}',
                f'        static_assert(std::is_same_v<decltype(m::{n}()), decltype(raw_{n})>);',
                f'        EXPECT_EQ(m::{n}(), raw_{n}) << "{n}";',
                f'#pragma pop_macro("{n}")']
    out.append('    };')
    out.append('    check();')
    out.append('    LengthUnits pixels(32.0f);')
    out.append('    check();')
    out.append('}\n')
    out.append('// ── computation macros ──────────────────────────────────────────────────────')
    for macro in functions:
        params = ', '.join(f'auto {p}' for p in macro.params)
        args = ', '.join(macro.params)
        arity = {1: 'unary', 2: 'binary'}[len(macro.params)]
        out.append(f'TEST(MacroFunctions, {macro.name}) {{')
        out.append(f'    {arity}([]({params}) {{')
        out += [f'        static_assert(std::is_same_v<decltype({macro.name}({args})), decltype((m::{macro.name})({args}))>);',
                f'        EXPECT_EQ({macro.name}({args}), (m::{macro.name})({args}));']
        out.append('    });')
        out.append('}')
    return '\n'.join(out) + '\n'


def outputs(root: Path) -> dict[Path, str]:
    sf = surface(fetch(root))
    return {
        root / 'src/box2d.cppm': render_root(sf),
        root / 'src/macros.cppm': render_macros(sf),
        root / 'tests/macros_mix_test.cpp': render_test(sf),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    stale = []
    for path, text in outputs(root).items():
        # Text mode: a checkout with CRLF line ends (Windows) reads the same.
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current == text:
            continue  # unchanged: the timestamp is kept, nothing rebuilds
        if args.check:
            stale.append(path.relative_to(root).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8', newline='\n')
            print('wrote', path.relative_to(root).as_posix())
    if stale:
        sys.exit('not what tools/gen_exports.py writes: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
